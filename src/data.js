// This is when Aimilios can actually take appointments in person — NOT the
// same as the phone/WhatsApp contact hours shown elsewhere on the site
// (those stay Δευ–Παρ 08:00–21:00, Σαβ 09:00–18:00; you can still call or
// message him any time in that window, he just may not be free to *do* the
// job until the hour below).
//   - Monday–Friday: only after 16:00
//   - Saturday: from the normal opening hour (09:00)
//   - Sunday: closed
// Change WEEKDAY_START_HOUR / SATURDAY_START_HOUR below if his availability
// ever changes — nothing else needs to be touched.
const WEEKDAY_START_HOUR = 16;
const SATURDAY_START_HOUR = 9;
const WEEKDAY_END_HOUR = 21;
const SATURDAY_END_HOUR = 18;

export function nextDays(n) {
  const days = [];
  const dowShort = ["Κυρ", "Δευ", "Τρι", "Τετ", "Πεμ", "Παρ", "Σαβ"];
  const today = new Date();
  for (let i = 0; i < n; i++) {
    const d = new Date(today);
    d.setDate(today.getDate() + i);
    const dow = d.getDay();
    const closed = dow === 0; // Sunday
    days.push({ date: d, label: dowShort[dow], num: d.getDate(), closed });
  }
  return days;
}

export function slotsFor(day) {
  if (!day) return [];
  const dow = day.date.getDay();
  const isSat = dow === 6;
  const startH = isSat ? SATURDAY_START_HOUR : WEEKDAY_START_HOUR;
  const endH = isSat ? SATURDAY_END_HOUR : WEEKDAY_END_HOUR;
  const out = [];
  for (let hr = startH; hr < endH; hr++) {
    out.push(hr + ":00");
    if (hr !== endH - 1) out.push(hr + ":30");
  }
  return out;
}

